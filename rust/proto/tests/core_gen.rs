/// A list field's rewrite in a proof: its lemma, the value it is about,
/// the field's value with `_` for it.
type Rewrite = (&'static str, String, String);

/// How one field is split in a decode∘encode proof: its cases, each a
/// pattern and the list rewrite it needs, if any.
fn cases(k: FieldKind, v: &str) -> Vec<(String, Option<Rewrite>)> {
    use FieldKind::*;
    match k {
        StrOmit => vec![("SNil{}".into(), None), (format!("SCon{{h_{v}, t_{v}}}"), None)],
        OptStr | OptStrOmit | OptNat | OptNatOmit | OptBoolOmit | OptJsonOmit => vec![("None{}".into(), None), (format!("Some{{x_{v}}}"), None)],
        OptStrsOmit => vec![("None{}".into(), None), (format!("Some{{x_{v}}}"), Some(("strs", format!("x_{v}"), "Some{_}".into())))],
        Strs => vec![(v.to_string(), Some(("strs", v.to_string(), "_".into())))],
        Nats => vec![(v.to_string(), Some(("nats", v.to_string(), "_".into())))],
        Msgs => vec![(v.to_string(), Some(("msgs", v.to_string(), "_".into())))],
        _ => vec![(v.to_string(), None)],
    }
}

fn rewritten(lemma: &str, x: &str, hole: &str) -> String {
    let (r, w) = match lemma {
        "strs" => ("K.strs", "K.jstrs"),
        "nats" => ("K.nats", "K.jnats"),
        _ => ("K.msgs", "K.jmsgs"),
    };
    hole.replace('_', &format!("{r}({w}({x}))"))
}

fn laws() -> String {
    let mut s = String::new();
    header(&mut s, "laws: each generated codec reads back what it writes; the tag table.");
    writeln!(s, "\nimport ./kit.bend as K\n").unwrap();
    for g in gens() {
        writeln!(s, "import ./{}.bend as {}\n", g.file, g.ty.to_uppercase()).unwrap();
    }
    for g in gens() {
        let m = g.ty.to_uppercase();
        let t = &g.t;
        writeln!(s, "# ---- {} ----\n", t.name).unwrap();
        // the tag table: each tag alone decodes to its record's defaults
        for k in t.kinds {
            let ds: Vec<String> = k.fields.iter().map(|f| default(f.kind).to_string()).collect();
            let law = format!("{}_{}_bare", g.prefix, k.tag);
            writeln!(s, "law {law}:").unwrap();
            writeln!(s, "  {{{m}.of(J.obj([J.kv(\"{}\", J.JStr{{\"{}\"}})])) == {m}.{} : {m}.{}}}\n", t.tag_key, k.tag, ctor(k, &ds), g.ty).unwrap();
            writeln!(s, "def {law}():\n  {{==}}\n").unwrap();
        }
        for (law, input) in [("unknown", format!("J.obj([J.kv(\"{}\", J.JStr{{\"weather\"}})])", t.tag_key)), ("untagged", "J.obj(Nil{})".to_string())] {
            let law = format!("{}_{law}_tag", g.prefix);
            writeln!(s, "law {law}:\n  {{{m}.of({input}) == {m}.{}{{}} : {m}.{}}}\n", g.fallback, g.ty).unwrap();
            writeln!(s, "def {law}():\n  {{==}}\n").unwrap();
        }
        // decode∘encode
        for k in records(t) {
            let law = format!("{}_{}_round", g.prefix, k.bend);
            round_law(&mut s, &law, &m, g.ty, k, &|x| format!("{m}.of({m}.json({x}))"));
        }
    }
    // the answer: each shape's fields read back what its encoder wrote
    // (which shape a line is, serde's untagged order, is Rust's: tests in
    // src/core/tests.rs and the fixture core_answer.jsonl)
    writeln!(s, "# ---- Answer ----\n").unwrap();
    for k in link::ANSWER.kinds {
        let law = format!("answer_{}_round", k.tag);
        round_law(&mut s, &law, "LINK", "Answer", k, &|x| format!("LINK.{}.of(LINK.answer_json({x}))", k.bend));
    }
    s
}

/// The law and proof that `lhs_of(record)`, its decode∘encode, is the
/// record: split on each field whose encoding has cases (omitted when
/// empty or none), each list field rewritten by its lemma.
fn round_law(s: &mut String, law: &str, m: &str, ty: &str, k: &Kind, lhs_of: &dyn Fn(&str) -> String) {
    {
        {
            let vars = field_vars(k);
            writeln!(s, "law {law}:").unwrap();
            for f in k.fields {
                writeln!(s, "  for {}: {}", var(f.name), bend_ty(f.kind)).unwrap();
            }
            let qual = |args: &[String]| format!("{m}.{}", ctor(k, args));
            writeln!(s, "  {{{} == {} : {m}.{ty}}}\n", lhs_of(&qual(&vars)), qual(&vars)).unwrap();
            writeln!(s, "def {law}({}):", vars.join(", ")).unwrap();
            let split: Vec<usize> = (0..k.fields.len()).filter(|&i| cases(k.fields[i].kind, &vars[i]).len() > 1).collect();
            let per: Vec<_> = k.fields.iter().zip(&vars).map(|(f, v)| cases(f.kind, v)).collect();
            // every combination of the split fields' cases
            let mut combos: Vec<Vec<usize>> = vec![vec![]];
            for &i in &split {
                combos = combos.into_iter().flat_map(|c| (0..per[i].len()).map(move |j| [c.clone(), vec![j]].concat())).collect();
            }
            let ind = if split.is_empty() { "  " } else { "      " };
            if !split.is_empty() {
                writeln!(s, "  match {}:", split.iter().map(|&i| vars[i].clone()).collect::<Vec<_>>().join(" ")).unwrap();
            }
            for c in combos {
                let mut args: Vec<String> = Vec::new();
                let mut rws: Vec<(usize, &'static str, String, String)> = Vec::new();
                for (i, p) in per.iter().enumerate() {
                    let j = split.iter().position(|&x| x == i).map_or(0, |n| c[n]);
                    let (pat, rw) = &p[j];
                    args.push(pat.clone());
                    if let Some((lemma, x, hole)) = rw {
                        rws.push((i, lemma, x.clone(), hole.clone()));
                    }
                }
                if !split.is_empty() {
                    let pats: Vec<String> = split.iter().map(|&i| args[i].clone()).collect();
                    writeln!(s, "    case {}:", pats.join(" ")).unwrap();
                }
                // each list field rewritten in turn: its hole `_`, the ones
                // before it already in their read-back form
                let lhs = lhs_of(&qual(&args));
                let mut rhs = args.clone();
                for (i, lemma, x, hole) in rws {
                    let mut with_hole = rhs.clone();
                    with_hole[i] = hole.clone();
                    writeln!(s, "{ind}%K.{lemma}_round({x}) : {{{lhs} == {} : {m}.{ty}}}", qual(&with_hole)).unwrap();
                    rhs[i] = rewritten(lemma, &x, &hole);
                }
                writeln!(s, "{ind}{{==}}").unwrap();
            }
            writeln!(s).unwrap();
        }
    }
}

