/// A Bend string literal of `t`.
fn bend_lit(t: &str) -> String {
    format!("\"{}\"", t.replace('\\', "\\\\").replace('"', "\\\"").replace('\n', "\\n"))
}

/// `bend/proofs/obs.bend`: per line of fixtures/obs_lines.jsonl, a law
/// that the generated encoder of its kind, given the record's values,
/// writes exactly its record line (what Rust's `ObsRec::line` writes and
/// reads): the format is pinned on both sides before the writers switch
/// (architect m_35725). The gate's PROOF step checks it.
fn obs_laws() -> String {
    let t = ObsRec::TABLE;
    let text = std::fs::read_to_string(root().join("rust/proto/fixtures/obs_lines.jsonl")).unwrap();
    let mut s = String::new();
    writeln!(s, "# generated by bise-proto (rust/proto/tests/core_gen.rs), never hand-edited:").unwrap();
    writeln!(s, "# {BLESS}=1 cargo test -p bise-proto --test core_gen").unwrap();
    writeln!(s, "# obs laws: each generated obs encoder writes the record line of rust/proto/fixtures/obs_lines.jsonl.").unwrap();
    writeln!(s, "import Base\n\nimport ../core/gen/obs.bend as OG\n").unwrap();
    for (n, l) in text.lines().filter(|l| !l.trim().is_empty()).enumerate() {
        let v: serde_json::Value = serde_json::from_str(l).unwrap();
        let rec = v["rec"].as_str().unwrap();
        let (kind, json) = rec.strip_prefix("obs ").and_then(|r| r.split_once(" :: ")).unwrap();
        let k = t.kinds.iter().find(|k| k.tag == kind).unwrap_or_else(|| panic!("no kind {kind}"));
        let o: serde_json::Value = serde_json::from_str(json).unwrap();
        let args: Vec<String> = k
            .fields
            .iter()
            .map(|f| match f.kind {
                FieldKind::Str => bend_lit(o[f.name].as_str().unwrap_or_default()),
                FieldKind::Nat => format!("{}n", o[f.name].as_u64().unwrap_or_default()),
                FieldKind::Bool => if o[f.name].as_bool() == Some(true) { "True{}" } else { "False{}" }.to_string(),
                k => panic!("obs field kind {k:?}: no literal"),
            })
            .collect();
        let law = format!("obs_line_{n}_{kind}");
        writeln!(s, "law {law}:\n  {{OG.{kind}({}) == {} : String}}\n\ndef {law}():\n  {{==}}\n", args.join(", "), bend_lit(rec)).unwrap();
    }
    s
}

