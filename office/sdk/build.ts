// Builds src/ into office/dist/office.js: one ESM bundle, no node imports
// (platform neutral, so an `fs` or `node:` import fails the build), the
// same bytes for the same sources and lockfile.
// A plugin's renderer bundle (architect m_60401) is built here too, from the plugin's own
// src/ (one lockfile: this folder's node_modules as esbuild's nodePaths), into the plugin's view
// folder: plugins/docs/src/markdown.ts and docx.ts into Writer's office-md.js (micromark + GFM)
// and office-view.js (docx-preview); plugins/media/src/pdfjs.ts and pdf-worker.ts into
// Preview's pdfjs.js and pdf.worker.js (pdf.js); plugins/sheets/src/sheet.ts into Sheets'
// office-sheet.js (Univer; built, never committed: scripts/bins.sh places it).
// Committed (cargo and nix never run pnpm); shipped in the app root
// (scripts/versions.sh), where the page server and bise office run read it.
// Beside each committed bundle, its types: <bundle>.d.ts re-exports its entry's
// (the SDK's tests, office/fixtures/make.ts, kit/office and the plugins' views import the bundle typed).
//
//   node build.ts           write ../dist/office.js and ../dist/office-view.js
//   node build.ts --check   rebuild in memory, exit 1 when a committed file differs
//                           (tests/office_check.sh, gate.sh)
// (node runs it by type stripping: office/sdk/.npmrc's node-options under pnpm)

import { build, type Loader, type Platform, type Plugin } from "esbuild";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const check = process.argv.includes("--check");
// --only <file> --out <path>: that one bundle to that path (scripts/bins.sh office-sheet)
const argOf = (name: string): string | undefined => {
  const i = process.argv.indexOf(name);
  return i < 0 ? undefined : process.argv[i + 1];
};
const only = argOf("--only");
const outArg = argOf("--out");
const banner = { js: "// generated by office/sdk/build.ts from office/sdk/src, never hand-edited:\n// pnpm -C office/sdk build (docs/office.md). Third-party code in it: THIRD_PARTY_NOTICES." };

// Modules a library requires that the SDK never runs (architect m_23798).
// Each becomes a stub that THROWS on any use, naming itself: a path we think
// is never taken fails loudly if it ever is. Any other node import still
// fails the office.js build (platform neutral). test/sheets-bare.test.ts
// runs the save and open paths with no node globals to prove none is touched.
const STUBS: { module: string; reason: string }[] = [
  // exceljs (src/sheets/io.ts drives its model and xforms, not its XLSX class)
  { module: "fs", reason: "exceljs file helpers: the SDK takes bytes, never paths" },
  { module: "readable-stream", reason: "exceljs parse-sax's old-stream branch: the SDK parses whole parts" },
  { module: "../utils/encryptor", reason: "exceljs sheet-password hashing (node crypto and Buffer): protect() without a password works" },
  { module: "../xlsx/xlsx", reason: "exceljs's XLSX class (JSZip and streams): src/sheets/io.ts replaces it" },
  { module: "../csv/csv", reason: "exceljs CSV (fast-csv and fs): not in the SDK" },
];
// Modules replaced by one of ours, for a reason (same rules: named, tested).
const REPLACED = [
  // exceljs ids for conditional-formatting extensions: same workbook, same bytes, no crypto.getRandomValues
  { module: "uuid", file: join(here, "src", "sheets", "ids.ts") },
];

const escape = (s: string): string => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
// any use (a call, a `new`, a property of what a property gave) throws the stub's words;
// reading a property at load (`const { PassThrough } = require(...)`) does not
const THROWING = `function (words) {
  const fail = () => { throw new Error(words); };
  const make = () => new Proxy(function () {}, {
    apply: fail, construct: fail, set: fail, defineProperty: fail,
    get: (_t, k) => (k === "then" || k === "__esModule" || typeof k === "symbol" ? undefined : make()),
  });
  return make();
}`;
const stubs: Plugin = {
  name: "office-stubs",
  setup(b) {
    const stubbed = new RegExp(`^(${STUBS.map((s) => escape(s.module)).join("|")})$`);
    b.onResolve({ filter: stubbed }, (a) => ({ path: a.path, namespace: "office-stub" }));
    b.onLoad({ filter: /.*/, namespace: "office-stub" }, (a) => {
      const stub = STUBS.find((s) => s.module === a.path);
      if (!stub) throw new Error(`office-stubs: no stub for ${a.path}`);
      const { module, reason } = stub;
      const words = JSON.stringify(`office: ${module} is not available (${reason})`);
      return { contents: `module.exports = (${THROWING})(${words});`, loader: "js" };
    });
    for (const r of REPLACED) {
      b.onResolve({ filter: new RegExp(`^${escape(r.module)}$`) }, () => ({ path: r.file }));
    }
  },
};

// office.js: the SDK, for bise office run, the views (~kit/office/v1/office.js) and the tests; no
//   DOM, no node; with the stubs above; fails past 3 MB (architect m_23769)
// office-view.js: what draws a docx in Writer (docx-preview + jszip), browser only, loaded by its
//   docx.js alone (architect m_23781); fails past 2 MB
// office-md.js: micromark + GFM, what draws a .md file in Writer (plugins/docs, its markdown.js
//   alone; md-artifact), platform neutral (no DOM, tested in node), minified, fails past 256 KB
// pdfjs.js and pdf.worker.js: pdf.js (pdfjs-dist, Apache-2.0), what draws a pdf in Preview
//   (plugins/media) and its worker, two files of its view's folder served under the view's own
//   script rule (architect m_24668: never a blob worker), loaded by its pdf.js alone; minified
//   (pdf.js ships its own minified builds), fail past 1 MB and 1.5 MB
// Univer's hyphenation patterns (85 languages, 5 MB): engine-render imports them by language
// for a docs layout that hyphenates; a cell never does. Each becomes an empty module.
const hyphenation: Plugin = {
  name: "univer-hyphenation",
  setup(b) {
    b.onResolve({ filter: /^\.\/[a-z]{2,4}(-[a-z0-9]+)*-[A-Za-z0-9_]{8}\.js$/ }, (a) =>
      /[\\/]@univerjs[\\/]engine-render[\\/]/.test(a.importer) ? { path: a.path, namespace: "univer-hyphenation" } : undefined,
    );
    b.onLoad({ filter: /.*/, namespace: "univer-hyphenation" }, () => ({ contents: "export {};", loader: "js" }));
  },
};

// office-sheet.js: Univer, Sheets' grid (page xlsx-univer), browser only, loaded by its book.js
//   alone; its stylesheet inside as text. NOT committed (architect m_37322: ~6.8 MB per rebuild
//   in a public history): built by scripts/bins.sh office-sheet into Sheets' view folder
//   (git-ignored), keyed by its inputs; --check leaves it to tests/office_check.sh.
//   Fails past 8 MB.
type Bundle = {
  file: string;
  /** from this folder (office/sdk) */
  entry: string;
  /** the folder it goes to, from the repo's root; none: office/dist */
  dir?: string;
  platform: Platform;
  max: number;
  mainFields?: string[];
  plugins?: Plugin[];
  loader?: Record<string, Loader>;
  define?: Record<string, string>;
  minify?: boolean;
  built?: boolean;
};
/** Preview's view folder (plugins/media): pdf.js and its worker go beside the view that loads them */
const PREVIEW = join("plugins", "media", "ai.mistral.vibe", "views", "preview");
const bundles: Bundle[] = [
  { file: "office.js", entry: join("src", "index.ts"), platform: "neutral", mainFields: ["module", "main"], plugins: [stubs], max: 3 * 1024 * 1024 },
  {
    file: "office-view.js",
    entry: join("..", "..", "plugins", "docs", "src", "docx.ts"),
    dir: join("plugins", "docs", "ai.mistral.vibe", "views", "writer"),
    platform: "browser",
    max: 2 * 1024 * 1024,
  },
  { file: "pdfjs.js", entry: join("..", "..", "plugins", "media", "src", "pdfjs.ts"), dir: PREVIEW, platform: "browser", minify: true, max: 1024 * 1024 },
  {
    file: "office-md.js",
    entry: join("..", "..", "plugins", "docs", "src", "markdown.ts"),
    dir: join("plugins", "docs", "ai.mistral.vibe", "views", "writer"),
    platform: "neutral",
    mainFields: ["module", "main"],
    minify: true,
    max: 256 * 1024,
  },
  { file: "pdf.worker.js", entry: join("..", "..", "plugins", "media", "src", "pdf-worker.ts"), dir: PREVIEW, platform: "browser", minify: true, max: 1.5 * 1024 * 1024 },
  {
    file: "office-sheet.js",
    entry: join("..", "..", "plugins", "sheets", "src", "sheet.ts"),
    dir: join("plugins", "sheets", "ai.mistral.vibe", "views", "grid"),
    platform: "browser",
    minify: true,
    built: true,
    plugins: [hyphenation],
    loader: { ".css": "text" },
    define: { "process.env.NODE_ENV": '"production"' },
    max: 8 * 1024 * 1024,
  },
];

// what V8 alone (bend-jsrt's script mode) and a browser lack: none may stay
const banned = [/\brequire\(\s*["']/, /from\s*["']node:/, /import\(\s*["']node:/, /\bprocess\.env\b/, /\bBuffer\.from\b/];

const repo = join(here, "..", "..");
const dist = join(here, "..", "dist");
let failed = false;
for (const b of bundles) {
  if (only !== undefined ? b.file !== only : b.built && check) continue;
  const dir = b.dir ? join(repo, b.dir) : dist;
  const out = only !== undefined && outArg ? outArg : join(dir, b.file);
  const res = await build({
    entryPoints: [join(here, b.entry)],
    // an entry in a plugin's src/ finds its packages here: one lockfile
    nodePaths: [join(here, "node_modules")],
    bundle: true,
    format: "esm",
    platform: b.platform,
    ...(b.mainFields ? { mainFields: b.mainFields } : {}),
    ...(b.plugins ? { plugins: b.plugins } : {}),
    ...(b.loader ? { loader: b.loader } : {}),
    ...(b.define ? { define: b.define } : {}),
    target: "es2022",
    write: false,
    minify: !!b.minify,
    charset: "utf8",
    legalComments: "eof",
    logLevel: "warning",
    banner,
  });
  const js = res.outputFiles?.[0]?.text;
  if (js === undefined) throw new Error(`${b.file}: esbuild gave no output`);
  const hit = b.platform === "neutral" && banned.find((re) => re.test(js));
  if (hit) {
    console.error(`${b.file} uses ${hit}: the bundle must run without node (docs/office.md)`);
    process.exit(1);
  }
  const size = new TextEncoder().encode(js).length;
  if (b.max && size > b.max) {
    console.error(`${b.file} is ${size} bytes, over its ${b.max} budget (architect m_23769, m_23781)`);
    process.exit(1);
  }
  emit(out, js);
  // its types, beside a committed bundle: its entry's, re-exported
  if (!b.built && only === undefined) {
    const dts = join(dir, b.file.replace(/\.js$/, ".d.ts"));
    const entry = relative(dir, join(here, b.entry)).split("\\").join("/");
    emit(dts, `${banner.js}\nexport * from "${entry.startsWith(".") ? entry : "./" + entry}";\n`);
  }
}
if (failed) process.exit(1);

// write a bundle (or its types), or with --check say whether the committed one is the same
function emit(out: string, text: string): void {
  const file = relative(repo, out).split("\\").join("/");
  if (check) {
    let have = "";
    try {
      have = readFileSync(out, "utf8");
    } catch {}
    if (have !== text) {
      console.error(`${file} is stale or hand-edited: run pnpm -C office/sdk build and commit it`);
      failed = true;
    } else console.log(`${file} is fresh (${text.length} bytes)`);
  } else {
    mkdirSync(dirname(out), { recursive: true });
    writeFileSync(out, text);
    console.log(`wrote ${file} (${text.length} bytes)`);
  }
}
