#!/usr/bin/env python3
"""No new hand-written JavaScript (js-to-ts, architect m_40557).

Every git-tracked .js/.mjs/.cjs must be generated (a "generated from" or "generated by"
banner in its first 3 lines: scripts/ts_emit.ts, office/sdk/build.ts), vendored
(bend/vendor/), or on tests/js_allowlist.txt with its reason. A new hand-written one fails:
write it in TypeScript.

    python3 tests/js_guard.py              check the repo (exit 1 on a stray file)
    python3 tests/js_guard.py --self-test  the rule on made-up files
"""
from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ALLOW = ROOT / "tests" / "js_allowlist.txt"
VENDORED = ("bend/vendor/",)
EXTS = (".js", ".mjs", ".cjs")


def allowlist(text: str) -> list[str]:
    """The allowlist's patterns: one per line, a '#' starts the reason (or a comment line)."""
    out = []
    for line in text.splitlines():
        pat = line.split("#", 1)[0].strip()
        if pat:
            out.append(pat)
    return out


def generated(head: str) -> bool:
    """A banner in the first 3 lines says the file is built from another."""
    first = "\n".join(head.splitlines()[:3]).lower()
    return "generated from" in first or "generated by" in first


def allowed(path: str, pats: list[str]) -> bool:
    """`dir/**`: anything under dir; a `*` (in dir too) stays inside one folder."""
    for p in pats:
        if p.endswith("/**"):
            if re.match("[^/]*".join(map(re.escape, p[:-2].split("*"))), path):
                return True
        elif re.fullmatch("[^/]*".join(map(re.escape, p.split("*"))), path):
            return True
    return False


def strays(files: list[tuple[str, str]], pats: list[str]) -> list[str]:
    """The files that are none of generated, vendored, allowed: (path, first bytes) in."""
    return [
        path for path, head in files
        if path.endswith(EXTS) and not path.startswith(VENDORED) and not generated(head) and not allowed(path, pats)
    ]


def self_test() -> None:
    pats = allowlist("a/keep.js  # why\n# a comment\nsite/hero/*.js # built\ndocs/spike/** # frozen\nplug/*/test/** # units\n")
    assert pats == ["a/keep.js", "site/hero/*.js", "docs/spike/**", "plug/*/test/**"], pats
    files = [
        ("kit/x.js", "// generated from x.ts by scripts/ts_emit.ts: never hand-edited\n"),
        ("office/dist/o.js", "// generated by office/sdk/build.ts from office/sdk/src\n"),
        ("bend/vendor/w.js", "// vendored\n"),
        ("a/keep.js", "// stays JS\n"),
        ("site/hero/film.js", "const a=1"),
        ("site/hero/deep/film.js", "const a=1"),
        ("docs/spike/ext/sw.js", "// spike"),
        ("plug/mermaid/test/a.test.mjs", "// a unit"),
        ("plug/mermaid/test/deep/b.test.mjs", "// a unit"),
        ("plug/a/b/test/c.test.mjs", "// * is one folder"),
        ("plug/mermaid/tests/d.mjs", "// not test/"),
        ("tools/new.mjs", "// hand-written\n"),
        ("kit/late.js", "// a\n// b\n// c\n// generated from late.ts\n"),
        ("kit/x.ts", "export {}"),
    ]
    got = strays(files, pats)
    assert got == ["site/hero/deep/film.js", "plug/a/b/test/c.test.mjs", "plug/mermaid/tests/d.mjs", "tools/new.mjs", "kit/late.js"], got
    print("js_guard self-test: ok")


def main() -> int:
    if "--self-test" in sys.argv:
        self_test()
        return 0
    pats = allowlist(ALLOW.read_text())
    listed = subprocess.run(
        ["git", "ls-files", "-z", "--", "*.js", "*.mjs", "*.cjs"], cwd=ROOT, check=True, capture_output=True
    ).stdout.decode().split("\0")
    files = []
    for path in filter(None, listed):
        p = ROOT / path
        if not p.is_file():
            continue  # deleted in the work tree, not yet in the index
        with p.open("rb") as f:
            files.append((path, f.read(600).decode("utf-8", "replace")))
    bad = strays(files, pats)
    if bad:
        print("js_guard: hand-written JavaScript outside the allowlist (write it in TypeScript, or add it to")
        print("tests/js_allowlist.txt with its reason):")
        for path in bad:
            print(f"  {path}")
        return 1
    print(f"js_guard: ok ({len(files)} js files: generated, vendored or allowed)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
